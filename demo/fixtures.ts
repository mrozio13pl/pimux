const reset = '\x1b[0m';
const bold = (text: string) => `\x1b[1m${text}${reset}`;
const dim = (text: string) => `\x1b[2m${text}${reset}`;
const cyan = (text: string) => `\x1b[36m${text}${reset}`;
const green = (text: string) => `\x1b[32m${text}${reset}`;
