export function transcriptFor(viewId: string): TranscriptChunk[] {
    const transcript = TRANSCRIPTS[viewId];
    if (!transcript) return [];
    const last = transcript.at(-1)!;
    return [
        { text: '\x1b[?25l', delay: 0 },
        ...transcript.slice(0, -1),
        { ...last, text: last.text.replace(/\r\n$/, '') },
    ];
}
